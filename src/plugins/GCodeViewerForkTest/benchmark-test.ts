// Throwaway TS-vs-WASM performance comparison - same pattern as standalone-test.ts (a real
// source-level import Vite transforms/resolves), run standalone via window.__runGcodeViewerBenchmark
export async function runBenchmark(lineCount = 200000): Promise<Record<string, unknown>> {
	const mod = await import("@duet3d/gcodeviewer");

	function buildFile(n: number): string {
		const lines = ["; benchmark file"];
		for (let i = 0; i < n; i++) {
			lines.push(`G1 X${i % 200} Y${(i * 2) % 200} Z${(i * 0.001).toFixed(3)} E${i} F1200`);
		}
		return lines.join("\n");
	}

	const bigFile = buildFile(lineCount);

	async function runOnce(useWasm: boolean) {
		const canvas = document.createElement("canvas");
		canvas.width = 100;
		canvas.height = 100;
		document.body.appendChild(canvas);
		const viewer = new mod.Viewer_Proxy(canvas);
		viewer.init();

		if (useWasm) {
			await viewer.enableWasmProcessing();
		}

		const wallStart = performance.now();
		const loadResult = await viewer.loadFile(bigFile);
		const wallTime = performance.now() - wallStart;

		const stats = await viewer.getProcessingStats();
		viewer.unload();
		canvas.remove();

		return { wallTime, loadResult, stats };
	}

	// TS-only first (a fresh Viewer_Proxy per run - enableWasmProcessing() is sticky per-processor)
	const tsRun = await runOnce(false);
	const wasmRun = await runOnce(true);

	return { lineCount, tsRun, wasmRun };
}

(window as any).__runGcodeViewerBenchmark = runBenchmark;

// TS-vs-WASM arc (G2/G3) parity check - P0-1 verification. A full circle plus a couple of
// straight moves before/after it, so a coordinate-swap bug in the arc path would corrupt the
// straight move that follows (this is exactly the "one arc poisons everything after it" bug
// P0-1 fixed).
export async function runArcComparison(): Promise<Record<string, unknown>> {
	const mod = await import("@duet3d/gcodeviewer");

	const arcGcode = [
		"; arc parity test file",
		"G28",
		"G90",
		"G1 X50 Y50 Z0.2 F1500",
		"G1 X60 Y50 E1 F1200", // straight move before the arc
		"G2 X60 Y50 I-10 J0 E3 F1200", // full clockwise circle, center (50,50), radius 10
		"G1 X70 Y50 E4 F1200", // straight move after the arc - would be corrupted by the old bug
		"G3 X50 Y70 I0 J20 E6 F1200", // counter-clockwise quarter arc
		"G1 X50 Y80 E7 F1200",
	].join("\n");

	async function runOnce(useWasm: boolean) {
		const canvas = document.createElement("canvas");
		canvas.width = 100;
		canvas.height = 100;
		document.body.appendChild(canvas);
		const viewer = new mod.Viewer_Proxy(canvas);
		const events: string[] = [];
		viewer.passThru = (e: any) => events.push(JSON.stringify(e).slice(0, 200));
		viewer.init();

		if (useWasm) {
			await viewer.enableWasmProcessing();
		}

		const loadResult = await viewer.loadFile(arcGcode);
		const stats = await viewer.getProcessingStats();
		viewer.unload();
		canvas.remove();

		return { loadResult, stats, events };
	}

	const tsRun = await runOnce(false);
	const wasmRun = await runOnce(true);

	return { tsRun, wasmRun };
}

(window as any).__runGcodeViewerArcComparison = runArcComparison;

