// P2-2 verification: cancelLoad() should now interrupt the WASM parser's own progress-callback
// loop mid-call, not just be detected once the whole synchronous call already returned. Compares
// wall time of a cancelled-almost-immediately load against a full uncancelled load of the same
// (large) file - the cancelled one should be dramatically faster if cancellation actually reaches
// inside the WASM call.
export async function runMidParseCancelTiming(lineCount = 500000): Promise<Record<string, unknown>> {
	const mod = await import("@duet3d/gcodeviewer");

	const lines = ["; mid-parse cancel timing file"];
	for (let i = 0; i < lineCount; i++) {
		lines.push(`G1 X${i % 200} Y${(i * 2) % 200} Z${(i * 0.001).toFixed(3)} E${i} F1200`);
	}
	const bigFile = lines.join("\n");

	const canvas1 = document.createElement("canvas");
	canvas1.width = 100;
	canvas1.height = 100;
	document.body.appendChild(canvas1);
	const fullViewer = new mod.Viewer_Proxy(canvas1);
	fullViewer.init();
	await fullViewer.enableWasmProcessing();
	const fullStart = performance.now();
	const fullResult = await fullViewer.loadFile(bigFile);
	const fullWallTime = performance.now() - fullStart;
	fullViewer.unload();
	canvas1.remove();

	const canvas2 = document.createElement("canvas");
	canvas2.width = 100;
	canvas2.height = 100;
	document.body.appendChild(canvas2);
	const cancelViewer = new mod.Viewer_Proxy(canvas2);
	cancelViewer.init();
	await cancelViewer.enableWasmProcessing();
	const cancelStart = performance.now();
	const cancelPromise = cancelViewer.loadFile(bigFile);
	setTimeout(() => cancelViewer.cancelLoad(), 5);
	const cancelResult = await cancelPromise;
	const cancelWallTime = performance.now() - cancelStart;
	cancelViewer.unload();
	canvas2.remove();

	return { lineCount, fullWallTime, fullResult, cancelWallTime, cancelResult };
}

(window as any).__runGcodeViewerMidParseCancelTiming = runMidParseCancelTiming;
